#!/usr/bin/env python3
"""Build docs/glossary.md from meta/glossary-terms.md (merged drafter staging).

- One `### Term` heading per term, grouped A–Z, with the L1 definition and a link to the
  chapter that introduced it.
- Every glossary anchor linked from a chapter (`glossary.md#slug`) must resolve: if a link's
  slug matches a term after normalization (e.g., parenthetical acronyms), an explicit
  `<a id="slug"></a>` alias is added. Unresolved anchors are listed in meta/glossary-missing.md
  so definitions can be added to meta/glossary-extra.md (same line format), which is merged too.
- Finally regenerates the root glossary.md via sync_root_files.py.
"""
from __future__ import annotations

import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from check_links import slugify  # noqa: E402

LINE = re.compile(r"^\s*[-*]\s*\*\*(.+?)\*\*\s*[—–-]+\s*(.+?)\s*$")


def chapter_paths() -> dict[str, str]:
    out = {}
    part = None
    for line in (ROOT / "meta" / "outline.md").read_text().splitlines():
        m = re.search(r"`docs/(\d\d-[a-z-]+)/`", line)
        if m:
            part = m.group(1)
            continue
        m = re.match(r"\|\s*([\d.]+)\s*\|\s*`([^`]+\.md)`", line)
        if m and part:
            key = re.match(r"(ch[\d-]+)", m.group(2)).group(1)
            out[key.rstrip("-")] = f"{part}/{m.group(2)}"
    return out


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def load_terms() -> dict[str, tuple[str, str, list[str]]]:
    terms: dict[str, tuple[str, str, list[str]]] = {}
    for src in ("glossary-terms.md", "glossary-extra.md"):
        p = ROOT / "meta" / src
        if not p.exists():
            continue
        for line in p.read_text(encoding="utf-8").splitlines():
            m = LINE.match(line)
            if not m:
                continue
            term, rest = m.group(1).strip(), m.group(2).strip()
            chs = re.findall(r"\((ch[\d.\-]+)\)\s*$", rest)
            rest = re.sub(r"\s*\((ch[\d.\-]+)\)\s*$", "", rest)
            k = norm(term)
            if k in terms:
                terms[k][2].extend(chs)
                continue
            terms[k] = (term, rest, chs)
    return terms


def linked_anchors() -> dict[str, list[str]]:
    out: dict[str, list[str]] = defaultdict(list)
    for f in sorted((ROOT / "docs").rglob("*.md")):
        if f.name == "glossary.md":
            continue
        for m in re.finditer(r"glossary\.md#([A-Za-z0-9_\-]+)", f.read_text(encoding="utf-8")):
            out[m.group(1)].append(f.name)
    return out


def main() -> int:
    terms = load_terms()
    chap = chapter_paths()
    by_slug = {slugify(t[0]): k for k, t in terms.items()}
    by_norm = {k: k for k in terms}
    # strip parentheticals for alias matching
    by_base = {norm(re.sub(r"\s*\(.*?\)", "", t[0])): k for k, t in terms.items()}
    aliases: dict[str, set[str]] = defaultdict(set)
    missing = {}
    for slug, files in linked_anchors().items():
        if slug in by_slug:
            continue
        n = slug.replace("-", "")
        k = by_norm.get(n) or by_base.get(n)
        if not k:
            # try prefix match (e.g., 'iceberg' -> 'apacheiceberg')
            cands = [kk for kk in terms if kk.endswith(n) or kk.startswith(n)]
            k = cands[0] if len(cands) == 1 else None
        if k:
            aliases[k].add(slug)
        else:
            missing[slug] = sorted(set(files))
    groups: dict[str, list[str]] = defaultdict(list)
    for k, (term, _, _) in terms.items():
        first = term[0].upper()
        groups[first if first.isalpha() else "#"].append(k)
    letters = sorted(groups)
    lines = [
        "# Glossary",
        "",
        f"> **{len(terms)} terms**, A–Z. Each entry is an L1 definition (one sentence you can use in conversation) "
        "and a link to the chapter where the term is explained. Generated by `scripts/build_glossary.py` from "
        "drafter submissions; edit `meta/glossary-terms.md` or `meta/glossary-extra.md`, not this file.",
        "",
        " · ".join(f"[{l}](#{l.lower() if l != '#' else 'numbers-and-symbols'})" for l in letters),
        "",
    ]
    for l in letters:
        lines += [f"## {l if l != '#' else 'Numbers and symbols'}", ""]
        for k in sorted(groups[l], key=lambda x: terms[x][0].lower()):
            term, d, chs = terms[k]
            for a in sorted(aliases.get(k, ())):
                lines.append(f'<a id="{a}"></a>')
            lines.append(f"### {term}")
            lines.append("")
            seen, refs = set(), []
            for c in chs:
                c = c.replace(".", "-")
                if c in chap and c not in seen:
                    seen.add(c)
                    refs.append(f"[{c.replace('ch', 'Ch ').replace('-', '.')}]({chap[c]})")
            lines.append(d + (f" *See {', '.join(refs)}.*" if refs else ""))
            lines.append("")
    (ROOT / "docs" / "glossary.md").write_text("\n".join(lines), encoding="utf-8")
    mm = ["# Glossary anchors linked from chapters but not defined", "",
          "Add a definition line for each to `meta/glossary-extra.md` (format: `- **Term** — definition. (chNN)`).", ""]
    mm += [f"- `{s}` — linked from {', '.join(f)}" for s, f in sorted(missing.items())]
    (ROOT / "meta" / "glossary-missing.md").write_text("\n".join(mm) + "\n", encoding="utf-8")
    subprocess.run([sys.executable, str(ROOT / "scripts" / "sync_root_files.py")], check=True)
    print(f"glossary: {len(terms)} terms, {sum(len(v) for v in aliases.values())} aliases, {len(missing)} missing anchors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
